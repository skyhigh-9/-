package curriculum_B;

public class Animal {
	private String name;

	public void setName(String name) {
		this.name = name;
	}

	public String getName() {
		return name;
	}

	private double body;

	public void setBody(double body) {
		this.body = body;
	}

	public double getBody() {
		return body;
	}

	private int fast;

	public void setFast(int fast) {
		this.fast = fast;
	}

	public int getFast() {
		return fast;
	}
}
